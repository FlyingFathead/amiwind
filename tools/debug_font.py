def readable_atlas():
    data=bytearray(128*128)
    for c in range(256):
        rows=GLYPHS.get(chr(c%128),[0]*7)
        # Console cursors and common slider/control marks retain visible forms.
        if c%128 in (10,11):rows=[31]*7 if c%128==11 else [0,0,0,0,0,0,31]
        for y,row in enumerate(rows):
            for x in range(5):
                if row & (1<<(4-x)):
                    data[((c//16)*8+y)*128+(c%16)*8+x+1]=254
    return bytes(data)
