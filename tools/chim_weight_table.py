"""The CHIMport order by weight: every cell not yet on CHIM, lightest first, grouped by region and town.

The maintainer's order (16 October 2026): the lightest cells first, then the heavier, the heaviest last, whole regions
where possible and never a town cut at the CHIM edge. This tool writes that order from data, never by hand:

  --progress FILE   the CHIM Progress Tracker's cell-progress.json (audits, stats, regions, names)
  --kept FILE       the cells already on CHIM (a cell file, or a build run's world-scenery/world-scenery.json)
  --run NAME=DIR    a CHIM world folder (chim-heap.json + chim-regions.json) measured with the current builder:
                    its frames' headroom replaces the tracker's figure for their cells (repeatable; later wins)
  --classes FILE    the weight classes (config/chim-weight-classes.json): thresholds are data, not code
  --seabed FILE     seabed cells (a LAND record under water) to plan as their own cells (CHIMPORT-OCEAN-LAND-41)

Two axes per cell: memory headroom (the least free bytes of its frame ring under the heap budget) and draw weight
(placed faces and placed models). Every figure names the build that measured it and when, and whether that build
is current (--current NAME, or a --run): a figure from an older builder is shown as such, never as a fresh one.

Towns: cells with the same place name (the part before a comma: "Vivec, Temple" is Vivec) that touch form a town;
a town and the cells around it go together. When one of them is not in an easy class, the whole town waits, named.

Outputs: --json (every row, region, town and the batch, with provenance), --cells-out (the batch as an
aw-chim-cells-1 file for tools/chim_cell_list.py --include), --md (a full table page) and --guide (the generated
section of the CHIMport guide, between its markers).

    python3 tools/chim_weight_table.py --progress cell-progress.json --kept world-scenery.json \\
        --classes config/chim-weight-classes.json --json weights.json --md docs/chim/CELL_WEIGHTS.md
"""
import argparse
import collections
import datetime
import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

FORMAT = 'aw-chim-weights-1'
CLASSES_FORMAT = 'aw-chim-weight-classes-1'
GUIDE_START = '<!-- weight table start: generated by tools/chim_weight_table.py, do not edit by hand -->'
GUIDE_END = '<!-- weight table end -->'
NEIGHBOURS = [(dx, dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1) if (dx, dy) != (0, 0)]


def key(cell):
    return '%d,%d' % tuple(cell)


def parse(k):
    x, y = k.split(',')
    return int(x), int(y)


def read_json(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def cell_set(path):
    """Cells of a cell file or of a run's world-scenery.json (chim_region_cells), as 'x,y' keys."""
    data = read_json(path)
    if isinstance(data, dict) and data.get('format') == 'aw-cell-run-1':     # a tracker run digest: its converted cells
        return {k for k, e in data['cells'].items() if e.get('converted')}
    if isinstance(data, dict) and 'chim_region_cells' in data:
        return {key(c) for c in data['chim_region_cells']}
    if isinstance(data, dict) and 'cells' in data:
        return {key(c) if isinstance(c, (list, tuple)) else str(c) for c in data['cells']}
    if isinstance(data, list):
        return {key(c) if isinstance(c, (list, tuple)) else str(c) for c in data}
    raise ValueError('%s: not a cell file' % path)


def load_classes(path):
    doc = read_json(path)
    if doc.get('format') != CLASSES_FORMAT:
        raise ValueError('%s: format must be %s' % (path, CLASSES_FORMAT))
    last = None
    for c in doc['classes']:
        if not isinstance(c.get('min_headroom_bytes'), int):
            raise ValueError('class %s: min_headroom_bytes must be a whole number of bytes' % c.get('id'))
        if last is not None and c['min_headroom_bytes'] > last:
            raise ValueError('classes must be listed heaviest headroom first (class %s)' % c['id'])
        last = c['min_headroom_bytes']
        mpf = c.get('max_placed_faces')
        if mpf is not None and mpf != 'median_shipped' and not isinstance(mpf, int):
            raise ValueError('class %s: max_placed_faces must be a number or "median_shipped"' % c['id'])
    ids = [c['id'] for c in doc['classes']] + [doc[k]['id'] for k in ('over', 'unmeasured', 'seabed')]
    unknown = sorted(set(doc.get('easy_batch', [])) - set(ids))
    if unknown:
        raise ValueError('easy_batch names unknown classes: ' + ', '.join(unknown))
    return doc


def frame_path(cell):
    return 'frames/x%+03d/y%+03d/frame.ccf' % tuple(cell)


def run_headroom(name, folder):
    """{cell key: figure} of a CHIM world folder: each frame's least headroom given to the cells it owns."""
    folder = Path(folder)
    heap = read_json(folder / 'chim-heap.json')
    table = read_json(folder / 'chim-regions.json')
    by_path = {f['frame']: f for f in heap.get('frames') or [] if f.get('headroom_bytes') is not None}
    when = datetime.datetime.fromtimestamp((folder / 'chim-heap.json').stat().st_mtime,
                                           datetime.timezone.utc).isoformat(timespec='seconds')
    out = {}
    for fr in table.get('frames') or []:
        f = by_path.get(frame_path(fr['cell']))
        if not f:
            continue
        for c in fr.get('cells') or [fr['cell']]:
            k = key(c)
            if k in out and out[k]['headroom_bytes'] <= f['headroom_bytes']:
                continue
            out[k] = {'headroom_bytes': f['headroom_bytes'], 'budget_bytes': f.get('budget_bytes'),
                      'peak_bytes': f.get('peak_bytes'), 'frame_ok': f.get('ok'), 'build': name, 'at': when,
                      'current': True, 'kind': fr.get('kind')}
    return out


def town_of(name):
    return (name or '').split(',')[0].strip()


def tracker_row(k, c, current):
    """Weight figures of one tracker cell, each with the build that measured it."""
    mem = c.get('audits', {}).get('memory_fit') or {}
    nums = mem.get('numbers') or {}
    head = nums.get('least_headroom')
    if head is None:
        head = (c.get('stats', {}).get('memory') or {}).get('least_headroom_bytes')
    prov = c.get('provenance') or {}
    build = mem.get('build') or prov.get('build')
    faces = (c.get('stats', {}).get('faces') or {}).get('chim_placed')
    chim = c.get('chim') or {}
    return {
        'cell': k, 'name': c.get('name') or '', 'region': c.get('region') or '', 'ring': c.get('ring'),
        'town': town_of(c.get('name')),
        'status': chim.get('bucket') or chim.get('status'), 'converted': bool(chim.get('converted')),
        'audits_ok': bool(chim.get('converted')) and chim.get('successful') is True,
        'failing': sorted(m for m, a in (c.get('audits') or {}).items() if a.get('status') == 'failed'),
        'headroom_bytes': head,
        'headroom_by': {'build': build, 'at': prov.get('built_at') if build == prov.get('build') else None,
                        'current': build in current} if head is not None else None,
        'placed_faces': faces,
        'placed_faces_by': {'build': prov.get('build'), 'at': prov.get('built_at'),
                            'current': prov.get('build') in current} if faces is not None else None,
        'placed_models': (c.get('contents') or {}).get('placements'),
        'placed_models_by': {'build': 'census of the masters', 'current': True},
    }


def classify(row, classes, median):
    if row.get('seabed'):
        return classes['seabed']['id']
    if not row['converted'] or row['headroom_bytes'] is None:
        if row['converted'] and not row['audits_ok']:
            return classes['over']['id']
        return classes['unmeasured']['id']
    if not row['audits_ok'] or row['headroom_bytes'] < 0:
        return classes['over']['id']
    for c in classes['classes']:
        if row['headroom_bytes'] < c['min_headroom_bytes']:
            continue
        mpf = c.get('max_placed_faces')
        if mpf == 'median_shipped':
            mpf = median
        if mpf is not None and (row['placed_faces'] is None or row['placed_faces'] >= mpf):
            continue
        return c['id']
    return classes['over']['id']


def towns(rows_by_cell):
    """[(town name, [cells])]: touching cells (8 neighbours) with the same place name."""
    by_name = collections.defaultdict(set)
    for k, r in rows_by_cell.items():
        if r['town']:
            by_name[r['town']].add(parse(k))
    out = []
    for name, cells in sorted(by_name.items()):
        left = set(cells)
        while left:
            seed = min(left)
            group, todo = {seed}, [seed]
            left.discard(seed)
            while todo:
                x, y = todo.pop()
                for dx, dy in NEIGHBOURS:
                    n = (x + dx, y + dy)
                    if n in left:
                        left.discard(n)
                        group.add(n)
                        todo.append(n)
            out.append((name, sorted(group)))
    return out


def make(progress, kept, classes, runs=(), seabed=(), current=(), island=1, hold=None):
    """The weights document (FORMAT). hold: {cell key: reason} for cells kept out of the batch by a decision
    (e.g. the inland lava group, whose method the maintainer picks first)."""
    hold = dict(hold or {})
    cells = progress['cells']
    current = set(current) | {name for name, _ in runs}
    measured = {}
    for name, figures in runs:
        measured.update(figures)
    shipped_faces = [(cells[k].get('stats', {}).get('faces') or {}).get('chim_placed') for k in kept if k in cells]
    shipped_faces = [f for f in shipped_faces if f is not None]
    median = int(statistics.median(shipped_faces)) if shipped_faces else None
    seabed = set(seabed)
    all_rows = {}
    for k, c in cells.items():
        if c.get('island') != island and k not in seabed:
            continue                # a seabed cell's tracker record has no island (no census row): the list names it
        if not c.get('land') and k not in seabed and k not in kept:
            continue
        r = tracker_row(k, c, current)
        if k in seabed:
            r['seabed'] = True
        if k in measured:
            m = measured[k]
            r['headroom_bytes'] = m['headroom_bytes']
            r['headroom_by'] = {'build': m['build'], 'at': m['at'], 'current': True}
        r['on_chim'] = k in kept
        r['hold'] = hold.get(k)
        all_rows[k] = r
    for r in all_rows.values():
        r['class'] = None if r['on_chim'] else classify(r, classes, median)
    easy = set(classes.get('easy_batch', []))
    seabed_id = classes['seabed']['id']
    # towns: a town and its ring of neighbours go together, or wait together
    town_rows = []
    held = {}
    for name, group in towns({k: r for k, r in all_rows.items() if r['town']}):
        unit = set(group)
        for x, y in group:
            unit |= {(x + dx, y + dy) for dx, dy in NEIGHBOURS}
        unit_keys = sorted(key(c) for c in unit if key(c) in all_rows)
        todo = [k for k in unit_keys if not all_rows[k]['on_chim']]
        if not todo:
            continue
        blockers = [k for k in todo if all_rows[k]['hold'] or
                    (all_rows[k]['class'] not in easy and all_rows[k]['class'] != seabed_id)]
        town_rows.append({'town': name, 'cells': [key(c) for c in group], 'unit': unit_keys, 'not_on_chim': todo,
                          'blockers': [{'cell': b, 'class': all_rows[b]['class'], 'name': all_rows[b]['name'],
                                        'hold': all_rows[b]['hold']} for b in blockers],
                          'joins': not blockers})
        if blockers:
            why = 'town %s waits for %s' % (name, ', '.join('%s (%s)' % (b, 'held' if all_rows[b]['hold'] else
                                                                            all_rows[b]['class']) for b in blockers))
            for k in todo:
                if k not in blockers:
                    held.setdefault(k, []).append(why)
    batch = sorted((k for k, r in all_rows.items() if not r['on_chim'] and k not in held and not r['hold'] and
                    (r['class'] in easy or (r['class'] == seabed_id and (r['converted'] or r['status'] == 'empty_sea')))), key=parse)
    order = {c['id']: i for i, c in enumerate(classes['classes'] + [classes[k] for k in ('seabed', 'over', 'unmeasured')])}
    todo_rows = sorted((r for r in all_rows.values() if not r['on_chim']),
                       key=lambda r: (order.get(r['class'], 99), -(r['headroom_bytes'] or -10 ** 12),
                                      r['placed_faces'] or 0, parse(r['cell'])))
    for r in todo_rows:
        r['batch'] = r['cell'] in batch
        r['held'] = held.get(r['cell'], []) + ([r['hold']] if r['hold'] else [])
    regions = []
    by_region = collections.defaultdict(list)
    for r in todo_rows:
        by_region[r['region'] or '(no region)'].append(r)
    for name in sorted(by_region):
        rows = by_region[name]
        heads = [r['headroom_bytes'] for r in rows if r['batch'] and r['headroom_bytes'] is not None]
        on = sum(1 for r in all_rows.values() if r['region'] == name and r['on_chim'])
        regions.append({'region': name, 'not_on_chim': len(rows), 'on_chim': on,
                        'by_class': dict(collections.Counter(r['class'] for r in rows)),
                        'batch': sum(1 for r in rows if r['batch']),
                        'held_by_town': sum(1 for r in rows if r['held']),
                        'whole_region': all(r['batch'] for r in rows),
                        'batch_headroom_min': min(heads) if heads else None,
                        'batch_headroom_max': max(heads) if heads else None,
                        'stays_out': [{'cell': r['cell'], 'class': r['class'], 'name': r['name'],
                                       'reason': '; '.join(r['held']) or reason_of(r, classes)}
                                      for r in rows if not r['batch']]})
    stale = collections.Counter((r['headroom_by'] or {}).get('build') for r in todo_rows
                                if r['batch'] and not r.get('seabed') and not (r['headroom_by'] or {}).get('current'))
    return {'format': FORMAT, 'classes': classes, 'median_shipped_placed_faces': median,
            'shipped_cells': len(kept), 'current_builds': sorted(current),
            'totals': {'not_on_chim': len(todo_rows), 'batch': len(batch),
                       'by_class': dict(collections.Counter(r['class'] for r in todo_rows)),
                       'held_by_town': sum(1 for r in todo_rows if r['held']),
                       'batch_figures_from_older_builds': dict(stale)},
            'regions': regions, 'towns': town_rows, 'batch': batch, 'rows': todo_rows}


def reason_of(row, classes):
    cid = row['class']
    if cid == classes['over']['id']:
        if row['failing']:
            return 'failing audits: ' + ', '.join(row['failing'])
        return 'over the memory budget' if (row['headroom_bytes'] or 0) < 0 else 'not passing its audits'
    if cid == classes['unmeasured']['id']:
        return 'not converted yet (%s)' % row['status'] if not row['converted'] else 'no headroom figure'
    if cid == classes['seabed']['id']:
        return 'seabed cell, to be converted as its own cell first (CHIMPORT-OCEAN-LAND-41)'
    return 'heavier than the easy batch (%s): next steps, lightest first' % cid


def mb(v):
    return '' if v is None else '%.2f' % (v / 1e6)


def by_text(by):
    if not by:
        return ''
    text = by.get('build') or '?'
    if by.get('at'):
        text += ', ' + by['at'][:10]
    return text + ('' if by.get('current') else ' (older builder)')


def render_md(doc, now):
    lab = {c['id']: c['label'] for c in doc['classes']['classes']}
    lab.update({doc['classes'][k]['id']: doc['classes'][k]['label'] for k in ('over', 'unmeasured', 'seabed')})
    t = doc['totals']
    lines = ['# CHIMport cells by weight', '',
             'Generated by `tools/chim_weight_table.py` on %s from the CHIM Progress Tracker data; do not edit by hand.'
             % now,
             'Every cell not yet on CHIM, lightest first. Headroom is the least free memory of the cell\'s frame ring '
             'under the CHIM heap budget (1 MB = 1,000,000 bytes); placed faces and placed models are its draw weight. '
             'Each figure names the build that measured it: "older builder" means it predates the current builder and '
             'is measured again before the batch is built ([the CHIMport guide](CHIMPORT.md#cells-by-weight)).', '',
             '%d cells not on CHIM; %d in the easy batch (%s); %d wait for their town or a named decision.' % (
                 t['not_on_chim'], t['batch'], ', '.join(doc['classes'].get('easy_batch', [])), t['held_by_town']), '',
             '| Cell | Place | Region | Class | Headroom (MB) | Measured by | Placed faces | Placed models | Batch |',
             '| --- | --- | --- | --- | ---: | --- | ---: | ---: | --- |']
    for r in doc['rows']:
        state = 'yes' if r['batch'] else ('waits: ' + '; '.join(r['held']) if r['held'] else 'no')
        lines.append('| %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (
            r['cell'], r['name'] or '-', r['region'] or '-', lab.get(r['class'], r['class']), mb(r['headroom_bytes']),
            by_text(r['headroom_by']), '' if r['placed_faces'] is None else '{:,}'.format(r['placed_faces']),
            '' if r['placed_models'] is None else '{:,}'.format(r['placed_models']), state.replace('|', '/')))
    return '\n'.join(lines) + '\n'


def render_guide(doc, now):
    lab = {c['id']: c['label'] for c in doc['classes']['classes']}
    t = doc['totals']
    cls = doc['classes']
    lines = [GUIDE_START, '',
             'Generated %s. Classes (`config/chim-weight-classes.json`, %s):' % (now, cls.get('status', 'set')), '']
    for c in cls['classes']:
        extra = ''
        if c.get('max_placed_faces') == 'median_shipped':
            extra = ' and placed faces below the median of the cells on CHIM (%s)' % (
                '{:,}'.format(doc['median_shipped_placed_faces']) if doc['median_shipped_placed_faces'] else 'none')
        elif c.get('max_placed_faces'):
            extra = ' and placed faces below {:,}'.format(c['max_placed_faces'])
        lines.append('- %s: at least %s MB of headroom%s' % (c['label'], mb(c['min_headroom_bytes']), extra))
    lines += ['- %s; %s; %s' % (cls['over']['label'], cls['unmeasured']['label'], cls['seabed']['label']), '',
              '%d cells are on CHIM; %d are not; the easy batch (%s) holds %d of them; %d wait for their town or a '
              'named decision.' % (doc['shipped_cells'], t['not_on_chim'], ', '.join(cls.get('easy_batch', [])),
                               t['batch'], t['held_by_town'])]
    if t['batch_figures_from_older_builds']:
        lines.append('Headroom figures of %d batch cells come from older builders (%s): the batch is measured again '
                     'with the current builder before it is built.' % (
                         sum(t['batch_figures_from_older_builds'].values()),
                         ', '.join('%s %d' % (k, v) for k, v in sorted(t['batch_figures_from_older_builds'].items(),
                                                                         key=lambda kv: -kv[1]))))
    lines += ['', '| Region | Not on CHIM | Easy batch | Whole region | Waiting (town or decision) | Batch headroom (MB) |',
              '| --- | ---: | ---: | --- | ---: | --- |']
    for r in doc['regions']:
        rng = '' if r['batch_headroom_min'] is None else '%s - %s' % (mb(r['batch_headroom_min']),
                                                                      mb(r['batch_headroom_max']))
        lines.append('| %s | %d | %d | %s | %d | %s |' % (r['region'], r['not_on_chim'], r['batch'],
                                                          'yes' if r['whole_region'] else 'no', r['held_by_town'], rng))
    lines += ['', 'Every cell with its figures and the build that measured them: [CHIMport cells by weight]'
              '(CELL_WEIGHTS.md).', '', GUIDE_END]
    return '\n'.join(lines)


def put_guide(path, section):
    text = Path(path).read_text(encoding='utf-8')
    a, b = text.find(GUIDE_START), text.find(GUIDE_END)
    if a < 0 or b < a:
        raise ValueError('%s: the weight table markers are missing' % path)
    text = text[:a] + section + text[b + len(GUIDE_END):]
    Path(path).write_text(text, encoding='utf-8', newline='\n')


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--progress', required=True)
    ap.add_argument('--kept', required=True, action='append')
    ap.add_argument('--classes', default=str(Path(__file__).resolve().parents[1] / 'config' / 'chim-weight-classes.json'))
    ap.add_argument('--run', action='append', default=[], metavar='NAME=DIR')
    ap.add_argument('--current', action='append', default=[], metavar='BUILD',
                    help='a tracker build name measured with the current builder')
    ap.add_argument('--seabed', action='append', default=[], metavar='FILE')
    ap.add_argument('--hold', action='append', default=[], metavar='FILE=REASON',
                    help='cells of FILE stay out of the batch with that reason (repeatable)')
    ap.add_argument('--island', type=int, default=1)
    ap.add_argument('--now', help='timestamp for the generated text (default: now, host clock)')
    ap.add_argument('--json')
    ap.add_argument('--cells-out')
    ap.add_argument('--md')
    ap.add_argument('--guide')
    a = ap.parse_args(argv)
    now = a.now or datetime.datetime.now().astimezone().strftime('%Y-%m-%d %H:%M %z')
    print('%s chim_weight_table: reading the tracker data (1 process; one pass over %s)' % (now, Path(a.progress).name))
    try:
        classes = load_classes(a.classes)
        kept = set()
        for path in a.kept:
            kept |= cell_set(path)
        runs = []
        for spec in a.run:
            name, _, folder = spec.partition('=')
            if not folder:
                raise ValueError('--run wants NAME=DIR, got %r' % spec)
            runs.append((name, run_headroom(name, folder)))
            print('  run %s: headroom for %d cells' % (name, len(runs[-1][1])))
        seabed = set()
        for path in a.seabed:
            seabed |= cell_set(path)
        hold = {}
        for spec in a.hold:
            path, _, why = spec.partition('=')
            if not why.strip():
                raise ValueError('--hold %s needs a reason (FILE=REASON)' % path)
            hold.update({k: why for k in cell_set(path)})
        doc = make(read_json(a.progress), kept, classes, runs, seabed, a.current, a.island, hold)
    except (ValueError, KeyError, OSError) as error:
        print('REFUSED: %s' % error, file=sys.stderr)
        return 2
    doc['generated'] = now
    t = doc['totals']
    print('  %d cells not on CHIM: %s' % (t['not_on_chim'], ', '.join('%s %d' % kv for kv in sorted(t['by_class'].items()))))
    print('  easy batch %d cells; %d wait for their town; batch figures from older builds: %s' % (
        t['batch'], t['held_by_town'], t['batch_figures_from_older_builds'] or 'none'))
    if a.json:
        Path(a.json).write_text(json.dumps(doc, indent=1) + '\n', encoding='utf-8', newline='\n')
        print('wrote', a.json)
    if a.cells_out:
        Path(a.cells_out).write_text(json.dumps({
            'format': 'aw-chim-cells-1', 'cells': [list(parse(k)) for k in doc['batch']],
            'reason': 'CHIMport easy batch by weight (%s)' % ', '.join(classes.get('easy_batch', [])),
            'notes': 'Made by tools/chim_weight_table.py %s: %d cells' % (now, len(doc['batch']))}, indent=1) + '\n',
            encoding='utf-8', newline='\n')
        print('wrote', a.cells_out)
    if a.md:
        Path(a.md).write_text(render_md(doc, now), encoding='utf-8', newline='\n')
        print('wrote', a.md)
    if a.guide:
        put_guide(a.guide, render_guide(doc, now))
        print('updated', a.guide)
    return 0


if __name__ == '__main__':
    sys.exit(main())
