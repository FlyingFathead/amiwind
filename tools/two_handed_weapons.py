#!/usr/bin/env python3
"""The two-handed weapons of the game, by type, as a generated section of docs/COMBAT.md.

The original decides by the weapon type (WPDT): long blade two hand (2), blunt two close (4), blunt two wide (5),
spear (6) and axe two hand (8) are two-handed melee weapons, and bows (9) and crossbows (10) take both hands too
(OpenMW 0.51 weapontype.cpp, the TwoHanded flag). Such a weapon plays the two-handed groups on the player's body
(weapontwohand for 2, 4, 8; weapontwowide for 5, 6; bowandarrow and crossbow) and takes the shield off when it is
equipped (engine/aga/src/aw_inventory.h AW_INV_TWO_HANDED).

Per type the section lists the number of records, the range of their chop, slash and thrust damage (bows and
crossbows: their damage) and the names: names and numbers only, read from the user's own game data, never typed by
hand. Run in the builder container on the owned data:

    python3 tools/two_handed_weapons.py --data-files /owned --write docs/COMBAT.md
    python3 tools/two_handed_weapons.py --data-files /owned --check docs/COMBAT.md   (exit 1 when the section is stale)
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
sys.path.insert(0, str(ROOT / 'tools'))

START = '<!-- two-handed weapons: generated by tools/two_handed_weapons.py, do not edit by hand -->'
STOP = '<!-- two-handed weapons end -->'
# (type, label, the group the body plays)
TYPES = ((2, 'Long blade, two-handed', 'weapontwohand'), (4, 'Blunt, two-handed close', 'weapontwohand'),
         (5, 'Blunt, two-handed wide (staffs, warhammers)', 'weapontwowide'), (6, 'Spear', 'weapontwowide'),
         (8, 'Axe, two-handed', 'weapontwohand'), (9, 'Bow', 'bowandarrow'), (10, 'Crossbow', 'crossbow'))
TWO_HANDED = tuple(t for t, _, _ in TYPES)


def rows_of(items):
    """{type: [(name, (chop lo, hi), (slash lo, hi), (thrust lo, hi))]} of the two-handed weapons in ITEMS
    (prepare_inventory.source_items: id -> {'kind', 'subtype', 'name', 'raw' (WPDT)}), sorted by name."""
    out = {t: [] for t in TWO_HANDED}
    for item in items.values():
        if item.get('kind') != 'WEAP' or item.get('subtype') not in out or len(item.get('raw') or b'') < 28:
            continue
        raw = item['raw']
        chop, slash, thrust = raw[22:24], raw[24:26], raw[26:28]
        out[item['subtype']].append((str(item.get('name') or item.get('id')), tuple(chop), tuple(slash), tuple(thrust)))
    for t in out:
        out[t].sort(key=lambda r: r[0].casefold())
    return out


def span(rows, k):
    lo = min(r[k][0] for r in rows)
    hi = max(r[k][1] for r in rows)
    return '%d-%d' % (lo, hi)


def render(rows):
    """The section's Markdown (between START and STOP)."""
    lines = [START, '', '| Type | Body group | Weapons | Chop | Slash | Thrust |', '| --- | --- | --- | --- | --- | --- |']
    for t, label, group in TYPES:
        r = rows.get(t, [])
        if not r:
            lines.append('| %s | `%s` | 0 | - | - | - |' % (label, group))
            continue
        ranged = t in (9, 10)
        lines.append('| %s | `%s` | %d | %s | %s | %s |' % (label, group, len(r), span(r, 1),
                                                            '-' if ranged else span(r, 2), '-' if ranged else span(r, 3)))
    lines.append('')
    lines.append('Bows and crossbows: the Chop column is their damage. The names, by type:')
    lines.append('')
    for t, label, _ in TYPES:
        names = [r[0].replace('|', '/') for r in rows.get(t, [])]
        lines.append('- **%s** (%d): %s' % (label, len(names), ', '.join(names) if names else 'none'))
    lines.append('')
    lines.append(STOP)
    return '\n'.join(lines)


def replace(page, section):
    if START not in page or STOP not in page:
        raise ValueError('The page has no two-handed weapons section markers')
    head, rest = page.split(START, 1)
    _, tail = rest.split(STOP, 1)
    return head + section + tail


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    p.add_argument('--data-files', required=True)
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument('--write')
    g.add_argument('--check')
    a = p.parse_args(argv)
    from prepare_inventory import source_items
    items = source_items(Path(a.data_files))
    items = items[0] if isinstance(items, tuple) else items
    section = render(rows_of(items))
    path = Path(a.write or a.check)
    page = path.read_text(encoding='utf-8')
    new = replace(page, section)
    if a.check:
        if new != page:
            print('two_handed_weapons: %s is stale; run --write' % path)
            return 1
        print('two_handed_weapons: %s is current' % path)
        return 0
    path.write_text(new, encoding='utf-8', newline='\n')
    counts = rows_of(items)
    print('two_handed_weapons: wrote %s (%s)' % (path, ', '.join('%d: %d' % (t, len(counts[t])) for t in TWO_HANDED)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
