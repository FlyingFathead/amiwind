def render(doc, today=None, inclusion=None, version=None):
    """The page text (LF, no trailing whitespace) for one aw-cell-progress-1 document."""
    today = today or datetime.datetime.now().astimezone().strftime('%Y-%m-%d %H:%M %z')
    cells = island_cells(doc, MAIN_ISLAND)
    total = len(cells)
    cl = classes(cells)
    done = sum(cl[k] for k in cp.COMPLETE_LEVELS) + cl['audits_passed'] + cl['empty_sea']
    eligible = sum(1 for c in cells if c['chim']['bucket'] in cp.ELIGIBLE)
    map_total, total = total, total - cl['ocean']
    land_total, land_done = total, done
    out = [HEADER, '', '# CHIM Cell Tracker', ''] + (updated_line(version, today) if version else []) + [
           'Live status of the open world on CHIM, Vvardenfell (island %d). Generated page: do not edit by hand. '
           'Per-cell detail is in the Toolkit and its CSV export. What each number counts: [what we count](#%s).' % (
               MAIN_ISLAND, COUNTING_ANCHOR), '',
           '**Conversion/audit progress: %s of %s (%s)**' % (n(done), n(total), pct(done, total)), '',
           'These audit totals count the cells with a LAND record (land and seabed), not cells included in a playable '
           'build; see Included in builds below.', ''] + group_lines(doc) + on_chim_lines(doc) + [
           'Map cells %s: cells with a LAND record %s (done %s, %s) and open-sea cells %s (no LAND record, not counted as done; the groups above say which are in the game and which are settled).' % (
               n(map_total), n(land_total), n(land_done), pct(land_done, land_total), n(cl['ocean'])), '',
           '- %s: %s' % (cp.COMPLETE_LABEL, n(cl['complete'])),
           '- %s: %s' % (cp.TERRAIN_COMPLETE_LABEL, n(cl['terrain_complete'])),
           '- %s: %s' % (cp.COMPLETE_UNLIT_LABEL, n(cl['complete_unlit'])),
           '- %s: %s' % (cp.TERRAIN_COMPLETE_UNLIT_LABEL, n(cl['terrain_complete_unlit'])),
           '- Passed (something still deferred): %s' % n(cl['audits_passed']),
           '- Empty sea: %s' % n(cl['empty_sea']),
           '- Open sea, no LAND record (not counted as done): %s' % n(cl['ocean']), '',
           '**Conversion-eligible: %s of %s** (every audit-done cell, lighting done or not; this is not a release assignment).' % (
               n(eligible), n(total)), ''] + lighting_lines(cells) + [
           '',
           'Generated %s. Tracker data generated %s.' % (today, doc.get('generated', 'unknown')), '']
    out += counting_lines(doc, inclusion) + ['## Totals', '']
    labels = {'complete': cp.COMPLETE_LABEL, 'terrain_complete': cp.TERRAIN_COMPLETE_LABEL,
              'complete_unlit': cp.COMPLETE_UNLIT_LABEL, 'terrain_complete_unlit': cp.TERRAIN_COMPLETE_UNLIT_LABEL, 'audits_passed': 'Passed (something still deferred)', 'empty_sea': 'Empty sea', 'ocean': 'Open sea',
              'hull_policy_pending': 'Hull policy pending', 'converted_failing': 'Failed',
              'not_converted': 'Not converted', 'not_started': 'Not started'}
    out += table(['Status', 'Cells', 'Share'], [(labels[k], n(v), pct(v, total)) for k, v in cl.items()])
    out += ['', 'Definitions are in the import policy below.', ''] + inclusion_lines(doc, inclusion) + release_lines(doc)
    out += ['## Per ring (ring 1 touches the sea)', '']
    rings = sorted({c['ring'] for c in cells if c.get('ring') is not None})
    rows = []
    for r in rings:
        rc = classes([c for c in cells if c.get('ring') == r])
        rows.append((r, n(sum(rc.values()))) + tuple(n(rc[k]) for k in cl))
    out += table(['Ring', 'Cells'] + [labels[k] for k in cl], rows)
    out += ['', '## Failures by mechanism class', '']
    fails, plain = collections.Counter(), 0
    for c in cells:
        if c['chim']['bucket'] != 'converted_failing':
            continue
        bad = [m for m, a in c['audits'].items() if a['status'] == 'failed']
        for m in bad:
            fails[m] += 1
        plain += 0 if bad else 1
    if fails or plain:
        rows = [(cp.MECHANISMS.get(m, m), n(fails[m])) for m in cp.MECHANISMS if fails[m]]
        if plain:
            rows.append(('Conversion error (no single failing audit)', n(plain)))
        out += table(['Mechanism', 'Cells'], rows)
        out += ['', 'A cell can fail more than one mechanism. Hull policy pending cells are not failures; they have their own line.']
    else:
        out += ['No failing cells.']
    out += ['', '## Per object type (converted cells, island-wide)', '']
    isl = [g for g in (doc.get('totals') or {}).get('islands', []) if g.get('island') == MAIN_ISLAND]
    out += category_lines(isl[0] if isl else None)
    out += [''] + interior_lines(doc) + policy_lines()
    text = '\n'.join(x.rstrip() for x in out) + '\n'
    return text


# Private paths and private volume names; words and tool names are checked by the release scan of the whole tree.
PRIVATE_PATTERNS = (re.compile(r'\b[A-Za-z]:[\\/]'), re.compile(r'(^|[\s(`])/(vol|src|out|owned|trk|met|perf)\b'),
                    re.compile(r'amiwind-[a-z0-9-]*-\d{3}'))


def private_hits(text):
    """Every line of text that looks like a private path, volume name or tool mention."""
    return [ln for ln in text.splitlines() if any(p.search(ln) for p in PRIVATE_PATTERNS)]


def policy_section(text):
    i = text.find('## Import policy')
    return text[i:] if i >= 0 else ''


def check(page_text, doc_for_policy=None):
    """Problems of a committed page: header missing, private content, or an import policy that no longer matches the code."""
    problems = []
    if not page_text.startswith(HEADER):
        problems.append('generated header missing')
    for ln in private_hits(page_text):
        problems.append('private content: ' + ln[:80])
    want = '\n'.join(x.rstrip() for x in policy_lines()) + '\n'
    if policy_section(page_text) != want:
        problems.append('import policy section is stale: run tools/cell_progress.py render-md')
    return problems
