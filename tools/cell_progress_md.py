def n(v):
    return '{:,}'.format(int(v))


def pct(a, b):
    return '%.1f %%' % (100.0 * a / b) if b else '0.0 %'


def table(head, rows, right_from=1):
    out = ['| ' + ' | '.join(head) + ' |',
           '| ' + ' | '.join(':--' if i < right_from else '--:' for i in range(len(head))) + ' |']
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return out


